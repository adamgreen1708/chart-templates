"""A deliberately synthetic unit-test fixture; never a production data source.

Run: python -m unittest tests.test_qa_story_discovery -v
No chart or published figure is generated by these tests.
"""
import copy
import csv
import tempfile
import unittest
from pathlib import Path

from scripts import qa_story_discovery as q


class StoryPreflightTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.original_root = q.REPO
        q.REPO = self.root
        self.rel = "data/test_titles.csv"
        path = self.root / self.rel
        path.parent.mkdir(parents=True)
        with path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, ["film", "group", "rating", "votes", "person"])
            writer.writeheader()
            writer.writerows([
                {"film": "Alpha", "group": "A", "rating": 4, "votes": 10, "person": "X"},
                {"film": "Beta", "group": "A", "rating": 6, "votes": 20, "person": "Y"},
                {"film": "Gamma", "group": "B", "rating": 8, "votes": 50, "person": "X"},
                {"film": "Delta", "group": "B", "rating": 10, "votes": 100, "person": "Z"},
            ])
        self.doc = {
            "project": "Synthetic regression only",
            "source": {"dataset": self.rel, "snapshot": "2026-11-19 source snapshot",
                       "grain": "one row per test film",
                       "coverage": "four synthetic records, not evidence for publication",
                       "limitations": ["Not real film research; regression fixture only"]},
            "central_question": "What do these invented test values reveal about scoring?",
            "editorial_takeaway": "This regression demonstrates calculations, not a real-world conclusion.",
            "evidence": [
                {"id": "avg_A", "kind": "calculation", "file": self.rel, "column": "rating",
                 "operation": "mean", "filter": {"column": "group", "equals": "A"},
                 "expected": 5, "tolerance": 1e-8},
                {"id": "share_A", "kind": "calculation", "file": self.rel, "column": "votes",
                 "operation": "percentage", "filter": {"column": "group", "equals": "A"},
                 "expected": 100*(30/180), "tolerance": 1e-8},
                {"id": "distinct_people", "kind": "calculation", "file": self.rel,
                 "column": "person", "operation": "distinct_count",
                 "expected": 3, "tolerance": 0},
                {"id": "source", "kind": "source", "url": "https://example.org/reference",
                 "checked_on": "2026-11-19", "claim": "Illustrative source format only"},
            ],
            "candidates": [
                {"id": "x", "claim": "Scores differ between categories",
                 "why_interesting": "Compare two grouped values with the rest of the sample",
                 "why_audience_cares": "The group distinction might help understand the example",
                 "weakness": "No external validity from this artificial test data",
                 "visual_direction": "Two-group annotated comparison",
                 "evidence_ids": ["avg_A"]},
                {"id": "y", "claim": "A small group has fewer votes",
                 "why_interesting": "A contrast between attention and average scores",
                 "why_audience_cares": "It exposes variation between engagement and quality",
                 "weakness": "All values are synthetic test values, not reality",
                 "visual_direction": "Chronological scatter with vote-size encoding",
                 "evidence_ids": ["share_A"],
                 "rejection_reason": "Less immediately explanatory than the group rating contrast"},
                {"id": "z", "claim": "Several titles share a named person",
                 "why_interesting": "This links otherwise separate entities in the dataset",
                 "why_audience_cares": "Relationships might explain the overlap of sample entities",
                 "weakness": "Artificial links have no real meaning outside unit tests",
                 "visual_direction": "Actual identity-to-film pathways",
                 "evidence_ids": ["distinct_people"],
                 "rejection_reason": "Artificial identity data is not usable for a real story"},
            ],
            "preferred_candidate": "x",
            "charts": [
                self.chart("01", "setup", "A controlled comparison with an explicit baseline",
                           "a grounded two-group comparison", "x"),
                self.chart("02", "tension", "Size and ratings reveal a different behaviour",
                           "the relationship varies by group", "y"),
                self.chart("03", "reveal", "A relationship hidden in the rows becomes visible",
                           "verified links reveal distinct entities", "z"),
            ],
            "render_contract": {"system": "github", "renderer": "src/render_538.py"},
        }
        self.doc["charts"][1]["annotations"] = [{
            "label": "Delta (largest number of votes)",
            "why_labelled": "Largest number of votes within all four records",
            "rule": {"kind": "max", "metric": "votes",
                     "identity_column": "film", "selected_identity": "Delta"}
        }]
        self.doc["charts"][2]["annotations"] = [{
            "label": "Alpha, a documented example",
            "why_labelled": "An intentionally chosen example rather than a maximum",
            "rule": {"kind": "editorial",
                     "criterion": "A fully sourced real exception would justify this marker"}
        }]

    def tearDown(self):
        q.REPO = self.original_root
        self.temp.cleanup()

    def chart(self, id, role, claim, takeaway, direction):
        return {
            "id": id, "role": role, "title": "A precise descriptive chart title",
            "question": "What can be learned from the selected group of values?",
            "claim": claim, "new_information": takeaway,
            "data_file": self.rel, "chart_type": "dot",
            "why_this_form": "Position makes comparison and differences apparent",
            "alternative_form": "Connected time line or grouped bar chart",
            "why_not_alternative": "The grouped bars add ink without a new finding",
            "scale_disclosure": "The axis is linear, with a zero baseline for bars",
            "encoding": [{"channel": "position", "field": "rating",
                          "meaning": "Source-derived rating for each sample film"}],
            "color_roles": [{"role": "Group A", "hex": "#C44E52"}],
            "annotations": [],
            "evidence_ids": ["avg_A" if role == "setup" else "share_A" if role == "tension" else "distinct_people"],
        }

    def reject(self, expected):
        with self.assertRaisesRegex(q.EditorialPreflightError, expected):
            q.validate(self.doc)

    def test_valid_source_derived_review_passes(self):
        result = q.validate(self.doc)
        self.assertEqual(result["charts"], 3)
        self.assertEqual(result["numeric_audits"], 3)

    def test_wrong_expected_arithmetic_rejected(self):
        self.doc["evidence"][0]["expected"] = 5.1
        self.reject("recomputed")

    def test_vote_share_bad_denominator_rejected(self):
        self.doc["evidence"][1]["expected"] = 30
        self.reject("recomputed")

    def test_wrong_labelled_leader_rejected(self):
        self.doc["charts"][1]["annotations"][0]["rule"]["selected_identity"] = "Beta"
        self.reject("not source-derived max")

    def test_unexplained_editorial_annotation_rejected(self):
        self.doc["charts"][2]["annotations"][0]["rule"]["criterion"] = ""
        self.reject("criterion")

    def test_conflicting_semantic_colour_rejected(self):
        self.doc["charts"][1]["color_roles"][0]["hex"] = "#1F8FA8"
        self.reject("semantic colour")

    def test_duplicate_story_route_rejected(self):
        self.doc["candidates"][2]["visual_direction"] = self.doc["candidates"][0]["visual_direction"]
        self.reject("only reworded versions")

    def test_unverified_rendering_not_github_rejected(self):
        self.doc["render_contract"]["system"] = "chatgpt"
        self.reject("MUST be in GitHub")

    def test_file_outside_repo_rejected(self):
        self.doc["charts"][0]["data_file"] = "../not-source.csv"
        self.reject("escapes repository")

    def test_missing_source_column_rejected(self):
        self.doc["evidence"][0]["column"] = "not_a_field"
        self.reject("missing metric column")

    def test_film_pair_count_must_not_impersonate_distinct_person_count(self):
        self.doc["evidence"][2]["operation"] = "count"
        self.doc["evidence"][2]["expected"] = 3
        self.reject("recomputed")


if __name__ == "__main__":
    unittest.main()
